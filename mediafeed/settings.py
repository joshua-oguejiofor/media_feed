    # Replace escaped string newlines with actual line breaks
    formatted_cert = SSL_CERT_CONTENT.replace("\\n", "\n")
    
    # Write to a secure temporary file
    temp_cert = tempfile.NamedTemporaryFile(delete=False, suffix=".crt")
    temp_cert.write(formatted_cert.encode("utf-8"))
    temp_cert.close()
    SSL_CERT_PATH = temp_cert.name




